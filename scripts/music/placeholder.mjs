// A diagnostic tune with Carrier's clock and section contract. No playback.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const out = path.join(root, "music/placeholder");
const sections = [
  ["calm", 8, [0, 8], null],
  ["grid", 4, null, "lap1"],
  ["lap1", 16, [8, 16], null],
  ["lap2", 8, [0, 8], null],
  ["hold", 5, [4, 5], null],
  ["fill", 2, null, "traced"],
  ["traced", 16, [8, 16], null],
  ["uplink", 8, null, "results"],
  ["results", 8, [0, 8], null],
];
const patches = ["chip-kick", "chip-snare", "chip-hat", "fm4-bass",
  "simple-sine", "bell", "chip-pulse", "simple-sine"];
const notes = ["D-5", "F-5", "A-5", "C-6", "E-5", "G-5", "D#5", "D-6", "A-4"];
let pos = 0;
const marks = [], patterns = [];
for (const [section, bars] of sections) {
  const index = marks.length;
  marks.push(`${section}: ${pos}`);
  for (let bar = 0; bar < bars; bar++, pos++) {
    const rows = [];
    for (let row = 0; row < 32; row++) {
      const cells = [];
      const add = (channel, note, volume = 48) =>
        cells.push(`(${channel} "${note}" ${channel} ${volume} "000")`);
      if (section === "grid") {
        if (row === 0) add(5, notes[index], 28);
        if (bar === 3 && [8, 16, 24].includes(row)) add(1, "C-2");
      } else {
        if (section !== "calm" && row % 8 === 0) add(1, "C-2", 56);
        if (section !== "calm" && row % 16 === 8) add(2, "C-4", 40);
        if (section !== "calm" && row % 2 === 0) add(3, "C-5", row % 8 === 0 ? 32 : 20);
        if (row % 2 === 0) add(4, bar % 2 ? "A-2" : "D-2", 40);
        if (row === 0) add(5, bar % 2 ? "A-3" : "D-3", 24);
        if (row === 0 || row === 16) add(6, notes[index], 36);
        if (["lap2", "fill", "traced", "uplink"].includes(section) && row % 8 === 4)
          add(7, row < 16 ? "A-5" : "D-6", 24);
        if (section === "traced" && [6, 22].includes(row)) add(8, "D#5", 20);
      }
      // Every section entry clears stems absent from its arrangement;
      // Motif's mark jumps preserve sounding voices between sections.
      if (bar === 0 && row === 0) {
        for (let channel = 1; channel <= 8; channel++) {
          if (!cells.some((cell) => cell.startsWith(`(${channel} `)))
            cells.push(`(${channel} "===" 0 0 "000")`);
        }
      }
      if (cells.length) rows.push(`      (row ${row} ${cells.join(" ")})`);
    }
    patterns.push(`    (pattern id: ${pos} rows: 32\n${rows.join("\n")})`);
  }
}
const instruments = patches.map((patch, index) =>
  `    (instrument id: ${index + 1} name: "ch${index + 1}" patch: (${patch}) volume: 48 gain: 0.5)`);
const tune = `;;; Diagnostic placeholder, generated by scripts/music/placeholder.mjs.
(tune version: 1 name: "Conductor placeholder" tempo: 140 speed: 3 channels: 8 meter: (8 4)
  (instruments
${instruments.join("\n")})
  (patterns
${patterns.join("\n")})
  (order ${Array.from({ length: pos }, (_, index) => index).join(" ")})
  (marks ${marks.join(" ")}))
`;
const cues = `;;; Loops are half-open, section-relative bars; #f means play through.
((id . placeholder)
 (engine-top-hz . 220.0)
 (engine-boost-hz . 293.664767917)
 (sections . (
${sections.map(([mark, , loop, next]) =>
  `   (${mark} (loop . ${loop ? `(${loop[0]} . ${loop[1]})` : "#f"}) (next . ${next || "#f"}))`).join("\n")}
  )))
`;
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, "parts.cts"), tune);
fs.writeFileSync(path.join(out, "cues.sgl"), cues);
console.log(`Placeholder: ${pos} bars, 140 BPM, eight channels; no audio device opened`);
